-- Run once in Supabase: SQL Editor → New query → Run.
-- The four rooms are open group chats for authenticated participants.
-- Phone numbers remain in Supabase Auth and are never copied to public tables.

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null default 'Участник' check (char_length(display_name) between 1 and 32),
  created_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  room_id text not null check (room_id in ('general', 'ideas', 'music', 'plans')),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  body text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now()
);

create index if not exists messages_room_created_at_idx
  on public.messages (room_id, created_at);

alter table public.profiles enable row level security;
alter table public.messages enable row level security;

drop policy if exists "Authenticated participants can read names" on public.profiles;
create policy "Authenticated participants can read names"
  on public.profiles for select to authenticated using (true);

drop policy if exists "Participants can add their own profile" on public.profiles;
create policy "Participants can add their own profile"
  on public.profiles for insert to authenticated with check (auth.uid() = id);

drop policy if exists "Participants can update their own profile" on public.profiles;
create policy "Participants can update their own profile"
  on public.profiles for update to authenticated
  using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "Authenticated participants can read messages" on public.messages;
create policy "Authenticated participants can read messages"
  on public.messages for select to authenticated using (true);

drop policy if exists "Participants can send as themselves" on public.messages;
create policy "Participants can send as themselves"
  on public.messages for insert to authenticated with check (auth.uid() = user_id);

grant select, insert, update on public.profiles to authenticated;
grant select, insert on public.messages to authenticated;
grant usage, select on sequence public.messages_id_seq to authenticated;

-- Enable realtime updates for newly sent messages.
alter publication supabase_realtime add table public.messages;
