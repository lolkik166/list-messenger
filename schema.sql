-- Run in Supabase SQL Editor. This script also upgrades the earlier chat schema.
-- Phone numbers remain in Supabase Auth and are never copied to public tables.

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null default 'Участник' check (char_length(display_name) between 1 and 32),
  created_at timestamptz not null default now()
);

create table if not exists public.rooms (
  id text primary key check (char_length(id) between 1 and 80),
  title text not null check (char_length(title) between 1 and 48),
  subtitle text not null default '',
  kind text not null check (kind in ('group', 'channel')),
  created_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now()
);

insert into public.rooms (id, title, subtitle, kind) values
  ('general', 'Общий чат', 'Открытая комната для участников', 'group'),
  ('ideas', 'Идеи и вдохновение', 'Делимся тем, что нас зажигает', 'group'),
  ('music', 'Музыка', 'Треки, которые хочется сохранить', 'group'),
  ('plans', 'Планы на вечер', 'Встречи и маленькие приключения', 'group')
on conflict (id) do nothing;

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  room_id text not null,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  body text not null check (char_length(body) between 1 and 2000),
  kind text not null default 'text',
  media_url text,
  created_at timestamptz not null default now()
);

-- Remove the old four-room-only constraint and allow custom groups and channels.
alter table public.messages add column if not exists kind text not null default 'text';
alter table public.messages add column if not exists media_url text;
alter table public.messages drop constraint if exists messages_room_id_check;
alter table public.messages drop constraint if exists messages_kind_check;
alter table public.messages add constraint messages_kind_check check (kind in ('text', 'voice'));
alter table public.messages drop constraint if exists messages_voice_media_check;
alter table public.messages add constraint messages_voice_media_check
  check ((kind = 'text' and media_url is null) or (kind = 'voice' and media_url is not null));

create index if not exists messages_room_created_at_idx on public.messages (room_id, created_at);

alter table public.profiles enable row level security;
alter table public.rooms enable row level security;
alter table public.messages enable row level security;

drop policy if exists "Authenticated participants can read names" on public.profiles;
create policy "Authenticated participants can read names"
  on public.profiles for select to authenticated using (true);

drop policy if exists "Participants can add their own profile" on public.profiles;
create policy "Participants can add their own profile"
  on public.profiles for insert to authenticated with check (auth.uid() = id);

drop policy if exists "Participants can update their own profile" on public.profiles;
create policy "Participants can update their own profile"
  on public.profiles for update to authenticated
  using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "Authenticated participants can read chats" on public.rooms;
create policy "Authenticated participants can read chats"
  on public.rooms for select to authenticated using (true);

drop policy if exists "Participants can create chats" on public.rooms;
create policy "Participants can create chats"
  on public.rooms for insert to authenticated with check (auth.uid() = created_by);

drop policy if exists "Authenticated participants can read messages" on public.messages;
create policy "Authenticated participants can read messages"
  on public.messages for select to authenticated using (true);

drop policy if exists "Participants can send to groups and their channels" on public.messages;
create policy "Participants can send to groups and their channels"
  on public.messages for insert to authenticated with check (
    auth.uid() = user_id and exists (
      select 1 from public.rooms
      where rooms.id = messages.room_id
        and (rooms.kind = 'group' or rooms.created_by = auth.uid())
    )
  );

grant select, insert on public.rooms to authenticated;
grant select, insert, update on public.profiles to authenticated;
grant select, insert on public.messages to authenticated;
grant usage, select on sequence public.messages_id_seq to authenticated;

-- Private Realtime topics are used for incoming call signaling and new chat notices.
drop policy if exists "Authenticated clients can listen to app realtime" on realtime.messages;
create policy "Authenticated clients can listen to app realtime"
  on realtime.messages for select to authenticated
  using (realtime.topic() like 'calls:%' or realtime.topic() = 'rooms:index');

drop policy if exists "Authenticated clients can send call signals" on realtime.messages;
create policy "Authenticated clients can send call signals"
  on realtime.messages for insert to authenticated
  with check (realtime.topic() like 'calls:%');

-- Private audio objects: only signed-in users can play, and users upload to their own folder.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('voice-messages', 'voice-messages', false, 10485760, array['audio/webm', 'audio/ogg', 'audio/mp4', 'audio/m4a']::text[])
on conflict (id) do update set public = false, file_size_limit = 10485760;

drop policy if exists "Authenticated users can listen to voice messages" on storage.objects;
create policy "Authenticated users can listen to voice messages"
  on storage.objects for select to authenticated using (bucket_id = 'voice-messages');

drop policy if exists "Users can upload their own voice messages" on storage.objects;
create policy "Users can upload their own voice messages"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'voice-messages' and (storage.foldername(name))[1] = auth.uid()::text);

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'messages'
  ) then
    alter publication supabase_realtime add table public.messages;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'rooms'
  ) then
    alter publication supabase_realtime add table public.rooms;
  end if;
end
$$;
